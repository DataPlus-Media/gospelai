// Run with PLAYWRIGHT_MODULE pointing to an installed Playwright module.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.STUDY_TEST_URL || `https://${process.env.REPLIT_DEV_DOMAIN}`;
async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/repl/tools/bin/chromium', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 402, height: 874 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => { errors.push(e.message); console.log('PAGE ERROR', e.message); });
  const go = async path => {
    await page.goto(`${base}${path}`);
    await page.getByText('Opening your local study…').waitFor({ state: 'hidden', timeout: 30000 });
  };
  const action = label => page.getByText(label, { exact: true }).click();
  const verseButton = (ref) => page.getByRole('button', { name: `Open actions for ${ref}`, exact: true });
  const chooseBook = async (filter, book) => {
    await page.getByRole('button', { name: filter }).click();
    await page.getByText('Choose a Bible book', { exact: true }).waitFor();
    await page.evaluate(() => {
      const scrollables = [...document.querySelectorAll('body *')].filter(el => el.scrollHeight > el.clientHeight + 50);
      const list = scrollables.at(-1);
      if (list) list.scrollTop = list.scrollHeight;
    });
    await page.getByRole('button', { name: book, exact: true }).click();
  };
  await page.goto(base);
  await page.getByRole('button', { name: 'Start exploring. Continue without an account.', exact: true }).click();
  await page.getByText('Continue reading', { exact: true }).waitFor({ timeout: 60000 });
  console.log('PASS guest welcome -> Today');
  assert.ok(await page.getByText('Verse of the Day', { exact: true }).count());

  await go('/bible?ref=John%203%3A16&jump=1');
  await verseButton('John 3:16').click();
  await action('Add bookmark');
  await verseButton('John 3:16').click();
  await action('Add highlight');
  await verseButton('John 3:16').click();
  await action('Write a note');
  await page.getByRole('textbox', { name: 'Your note' }).fill('My John 3:16 reflection');
  await page.getByRole('button', { name: 'Save note' }).click();
  await page.getByText('Note saved on this device.', { exact: true }).waitFor();
  await go('/saved');
  await page.getByText('John 3:16 · KJV · bookmark', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Highlights', exact: true }).click();
  await page.getByText('John 3:16 · KJV · highlight', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Bookmarks', exact: true }).click();
  await page.getByRole('button', { name: 'Read John 3:16', exact: true }).first().click();
  await verseButton('John 3:16').waitFor();
  await page.waitForFunction(() => {
    const verse = document.querySelector('[aria-label="Open actions for John 3:16"]');
    if (!verse) return false;
    const rect = verse.getBoundingClientRect();
    return rect.top >= 310 && rect.bottom <= innerHeight;
  });
  assert.ok(await verseButton('John 3:16').isVisible());
  console.log('PASS bookmarks + highlights survive reload and open exact verse');

  await verseButton('John 3:16').click();
  await action('Copy verse');
  await page.getByText('Verse copied.', { exact: true }).waitFor();
  await verseButton('John 3:16').click();
  let chatRequests = 0;
  await context.route('**/api/chat', async route => {
    chatRequests++;
    if (chatRequests === 1) await route.abort('internetdisconnected');
    else await route.fulfill({ json: { reply: 'Test explanation: read the surrounding passage.' } });
  });
  await action('Ask GospelAI · edit draft first');
  const input = page.getByRole('textbox', { name: 'Write a message' });
  await input.waitFor();
  assert.equal(chatRequests, 0);
  assert.ok((await input.inputValue()).includes('John 3:16 (KJV)'));
  assert.ok((await input.inputValue()).includes('For God so loved the world'));
  assert.equal(await input.evaluate(el => el === document.activeElement), false);
  await input.fill((await input.inputValue()) + 'Explain this simply.');
  await page.getByRole('button', { name: 'Send message' }).click();
  await page.getByText('Try again', { exact: true }).waitFor();
  assert.equal(chatRequests, 1);
  await page.getByRole('button', { name: 'Try again' }).click();
  await page.getByText('Test explanation: read the surrounding passage.', { exact: true }).waitFor();
  assert.equal(chatRequests, 2);
  console.log('PASS actual verse draft, editable, no auto-focus/send; connection failure and retry (stubbed AI)');
  await page.getByRole('button', { name: 'GospelAI, return to Today', exact: true }).click();
  await page.getByText('Continue reading', { exact: true }).waitFor();
  console.log('PASS chat header returns Today without loop');
  await go('/notes');
  await page.getByText('My John 3:16 reflection', { exact: true }).waitFor();
  await chooseBook('Notes book filter: All books', 'John');
  await go('/today');
  await go('/notes');
  await page.getByRole('button', { name: 'Notes book filter: John' }).waitFor();
  await page.getByRole('button', { name: 'Edit note for John 3:16' }).click();
  await page.getByRole('textbox', { name: 'Your note' }).fill('Edited John 3:16 reflection');
  await page.getByRole('button', { name: 'Save note changes' }).click();
  await page.getByText('Edited John 3:16 reflection', { exact: true }).waitFor();
  await go('/saved');
  await page.getByRole('button', { name: 'Highlights', exact: true }).click();
  await chooseBook('Highlights book filter: All books', 'Romans');
  await go('/today');
  await go('/saved');
  await page.getByRole('button', { name: 'Highlights', exact: true }).click();
  await page.getByRole('button', { name: 'Highlights book filter: Romans' }).waitFor();
  await page.getByRole('button', { name: 'Bookmarks', exact: true }).click();
  await page.getByRole('button', { name: 'Remove bookmark for John 3:16' }).click();
  await page.getByRole('button', { name: 'Highlights', exact: true }).click();
  await page.getByRole('button', { name: 'Remove highlight for John 3:16' }).click();
  await page.getByText('No highlights for Romans yet.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Notes', exact: true }).first().click();
  await page.getByRole('button', { name: 'Delete note for John 3:16' }).click();
  await page.getByText('No notes for John yet.', { exact: true }).waitFor();
  await go('/saved');
  await page.getByRole('button', { name: 'Bookmarks', exact: true }).click();
  await page.getByText(/No bookmarks yet\./).waitFor();
  console.log('PASS note editing/deletion, independent saved filters and explicit bookmark/highlight removals');
  await go('/today');
  await page.getByRole('button', { name: 'Continue reading John 3:16', exact: true }).waitFor();
  assert.equal(await page.getByText('Seven days in the Word', { exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Start plan', exact: true }).count(), 0);
  assert.equal(await page.getByText('Reset plan progress', { exact: true }).count(), 0);
  console.log('PASS reading position restart persistence; reading plan is absent from Today');

  await go('/bible?ref=John%203%3A16&jump=2');
  const versionControl = page.getByRole('button', { name: 'Bible version: King James Version, the only available version' });
  await versionControl.waitFor();
  assert.equal(await versionControl.isDisabled(), true);
  await page.getByRole('button', { name: 'Increase Bible text size' }).click();
  await page.getByLabel('Bible text size 18').waitFor();
  await page.getByRole('button', { name: 'Choose Bible book. Current book: John' }).click();
  await page.getByPlaceholder('Search books (e.g., John, Romans)…').fill('Matthew');
  await page.getByText('Matthew', { exact: true }).first().click();
  await page.getByText('10', { exact: true }).last().click();
  await verseButton('Matthew 10:2').waitFor();
  await verseButton('Matthew 10:2').click();
  await page.getByText('Matthew 10:2 · KJV', { exact: true }).waitFor();
  await action('Add bookmark');
  await verseButton('Matthew 10:2').click();
  await action('Add highlight');
  await verseButton('Matthew 10:2').click();
  await action('Authors insight · this verse');
  await page.getByText('Matthew 10:2', { exact: true }).waitFor();
  await page.getByTestId('selected-scripture-text').waitFor();
  assert.ok(await page.getByTestId('selected-scripture-text').innerText().then(text => text.includes('James [the son] of Zebedee')));
  await page.getByRole('button', { name: 'Close passage insight' }).click();
  await go('/bible?ref=Matthew%2010%3A2&jump=4');
  await verseButton('Matthew 10:2').click();
  await action('Copy verse');
  await page.getByText('Verse copied.', { exact: true }).waitFor();
  await verseButton('Matthew 10:2').click();
  await action('Ask GospelAI · edit draft first');
  const matthewDraft = page.getByRole('textbox', { name: 'Write a message' });
  await matthewDraft.waitFor();
  assert.ok((await matthewDraft.inputValue()).includes('Matthew 10:2 (KJV)'));
  assert.ok((await matthewDraft.inputValue()).includes('James [the son] of Zebedee'));
  await page.getByRole('button', { name: 'GospelAI, return to Today', exact: true }).click();
  await page.getByText('Continue reading', { exact: true }).waitFor();
  await go('/bible?ref=Matthew%2010%3A2&jump=3');
  await verseButton('Matthew 10:2').click();
  await action('Write a note');
  await page.getByRole('textbox', { name: 'Your note' }).fill('Matthew 10:2 canonical note');
  await page.getByRole('button', { name: 'Save note' }).click();
  await page.getByText('Note saved on this device.', { exact: true }).waitFor();
  await go('/notes');
  await chooseBook('Notes book filter: John', 'All books');
  await page.getByText('Matthew 10:2 · Bible', { exact: true }).waitFor();
  await page.getByText('Matthew 10:2 canonical note', { exact: true }).waitFor();
  await page.getByRole('link', { name: 'Open Matthew 10:2 in Bible' }).click();
  await verseButton('Matthew 10:2').waitFor();
  await go('/saved');
  await page.getByText('Matthew 10:2 · KJV · bookmark', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Highlights', exact: true }).click();
  await page.getByText('Matthew 10:2 · KJV · highlight', { exact: true }).waitFor();
  console.log('PASS Matthew 10:2 stays canonical through book/chapter choice, bookmark, highlight, Authors insight, chat, copy, and note');

  assert.deepEqual(errors, []);
  await browser.close();
}
main().catch(e => { console.error(e); process.exit(1); });
